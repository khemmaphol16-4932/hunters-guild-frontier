const part = (cls, id, desc, cell, { tiers = [1, 2, 3], rotations = 2, priority = 'P0', extra } = {}) => ({
  id: `BLD_KIT_${cls}_${id.toUpperCase()}`, priority, canvas: cell, pivot: [cell[0] / 2, cell[1] - 16],
  out: `${kit}/${cls.toLowerCase()}/bld_kit_${cls.toLowerCase()}_${id}_t${tiers.includes(2) ? 2 : tiers[0]}_n@2x.png`,
  subject: `Modular building-kit part for a frontier town, ${tiers.includes(2) ? TIER[2] : TIER[tiers[0]]}: ${desc}. One tile wide, designed to snap cleanly to neighbouring kit parts on the tile grid, facing north.`,
  negative: extra ?? 'whole building, adjacent buildings',
  variations: [
    ...tiers.filter((t) => t !== (tiers.includes(2) ? 2 : tiers[0])).map((t) => `the material tier, to ${TIER[t]}; same shape, same snap edges.`),
    rotations === 4 ? 'the rotation, to east, drawn fresh — this part has a sided feature and must not be mirrored.' : 'the rotation, to east (west is generated by mirroring east).',
    ...(rotations === 4 ? ['the rotation, to south, drawn fresh.', 'the rotation, to west, drawn fresh.'] : []),
  ],
});

