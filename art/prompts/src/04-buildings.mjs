const FOUR_WAY = new Set(['guild_hall', 'smithy', 'watchtower', 'market_stall']);
const P0 = new Set(['guild_hall', 'bunkhouse', 'granary', 'field_kitchen', 'infirmary', 'market_stall']);
const P2 = new Set(['bathhouse', 'tannery', 'quarry_camp', 'research_annex', 'drill_yard', 'shrine']);

const reference = (b) => {
  const { width: w, height: h } = b.footprint;
  const cw = (w + h) * 64;
  const first = b.tiers[0];
  const name = (t) => t.name ?? `${b.name} tier ${t.tier}`;
  const brief = BRIEF[b.id] ?? (() => { throw new Error(`04-buildings: no brief for ${b.id}`); })();
  return {
    id: `BLD_REF_${b.id.toUpperCase()}`, priority: P0.has(b.id) ? 'P0' : P2.has(b.id) ? 'P2' : 'P1',
    canvas: [cw, (w + h) * 32 + 200], pivot: [cw / 2, (w + h) * 32 + 184], covers: [`building:${b.id}`],
    out: `art/buildings/reference/bld_ref_${b.id}_t${first.tier}_n@2x.png`,
    subject: `Reference render of the ${b.name} ("${name(first)}") in a frontier hunters' guild town: ${brief}. ${TIER[first.tier]}. Its category identity: ${IDENTITY[b.category]}. Footprint exactly ${w} by ${h} tiles on a 64 by 32 pixel tile grid (${cw} pixels wide at 2x), facing north. Built by people who needed it quickly and then kept improving it.`,
    variations: [
      ...b.tiers.slice(1).map((t) => `the tier, to "${name(t)}" — ${TIER[t.tier]}. Same footprint, same orientation, same entrance; it must read as the same place improved.`),
      FOUR_WAY.has(b.id) ? 'the rotation, to east, drawn fresh — its sided features must stay on the correct wall.' : 'the rotation, to east.',
    ],
    note: 'A target, not a shipped sprite: the kit recipe in src/data/town/building-art.json must reproduce this look (O-6).',
  };
};

